source("new/code/figure_style.R")
z <- read_result("E2/E2_complete_score_joint_bootstrap_summary.csv")
stopifnot(nrow(z) == 10, all(z$B_valid == 2000))
labels <- c("Equal-weight Rel", "Raw R-squared", "Clipped R-squared", "Pearson", "Clipped Pearson", "R-squared weight 0.25", "R-squared weight 0.75", "Calibration RMSE rank", "Training mean", "Training variance")
z <- z[match(c("Rel_equal", "R2_raw", "R2_clipped", "Pearson", "Pearson_clipped", "Rel_R2_weight_025", "Rel_R2_weight_075", "Calibration_RMSE_rank", "Training_native_mean", "Training_native_variance"), z$score), ]
export_plot("F_E2_score_ablation", function() {
  par(mfrow = c(1, 2), mar = c(4.2, 9.7, 1.6, .9), mgp = c(2.6, .7, 0), las = 1, cex = 1)
  y <- rev(seq_len(nrow(z)))
  plot(z$bootstrap_median_rho, y, type = "n", xlim = c(-.73, -.22), ylim = c(.5, 13), yaxt = "n", xlab = "Spearman correlation with test RMSE", ylab = "", bty = "l")
  axis(2, at = y, labels = labels, tick = FALSE)
  segments(z$rho_CI_q025, y, z$rho_CI_q975, y, col = "#777777", lwd = 1.4)
  points(z$bootstrap_median_rho, y, pch = 15, col = pal["Rel"])
  points(z$point_rho_vs_test_RMSE, y + .13, pch = 1, col = "black")
  legend("topright", c("Original-sample estimate", "Bootstrap median / 95% interval"), pch = c(1, 15), col = c("black", pal["Rel"]), bty = "n", cex = .95)
  panel_letter("A")
  par(mar = c(4.2, 1.1, 1.6, .9))
  plot(z$bootstrap_median_baseline_minus_Rel, y, type = "n", xlim = c(-.22, .27), ylim = c(.5, 13), yaxt = "n", xlab = "Correlation difference: baseline minus Rel", ylab = "", bty = "l")
  abline(v = 0, lty = 2, col = "#999999")
  segments(z$contrast_CI_q025, y, z$contrast_CI_q975, y, col = "#777777", lwd = 1.4)
  points(z$bootstrap_median_baseline_minus_Rel, y, pch = 15, col = pal["Rel"])
  points(z$point_rho_baseline_minus_Rel, y + .13, pch = 1)
  panel_letter("B")
}, width = 10, height = 5.2)
