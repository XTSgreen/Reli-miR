source("new/code/figure_style.R")
z <- read_result("harmonized/E4/E4_external_metrics_by_miRNA.csv")
stopifnot(nrow(z) == 742)
export_plot("F_E4_external_transfer", function() {
  par(mfrow = c(1, 2), mar = c(5, 4.4, 1.4, .8), mgp = c(3.6, .7, 0), cex = .9, las = 1)
  plot(z$internal_Rel, z$Pearson, pch = 16, cex = .55, col = adjustcolor(pal["Rel"], .45), xlab = "Internal calibration Rel", ylab = "External Pearson correlation", bty = "l", ylim = c(-1, 1))
  abline(h = .5, lty = 2, col = "#999999")
  panel_letter("A")
  subsets <- c(list(z$R2), lapply(c(.5, .6, .7), function(th) z$R2[z$internal_Rel >= th]))
  names(subsets) <- c("All", "Rel >= 0.5", "Rel >= 0.6", "Rel >= 0.7")
  stopifnot(identical(unname(lengths(subsets)), c(742L, 170L, 72L, 32L)))
  boxplot(subsets, names = rep("", 4), outline = FALSE, col = c("#EEEEEE", rep(adjustcolor(pal["Rel"], .35), 3)), ylab = "External R-squared", xlab = "Fixed internal score selection", bty = "l", xaxt = "n")
  axis(1, at = 1:4, labels = names(subsets))
  mtext(paste0("(n=", lengths(subsets), ")"), side = 1, at = 1:4, line = 1.9, cex = .85)
  abline(h = 0, lty = 2, col = "#888888")
  panel_letter("B")
}, width = 8.5, height = 3.8)
